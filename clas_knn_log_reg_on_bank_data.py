def Pred_func(age, job, marital, education, housing, loan, contact, month, day_of_week, duration, campaign, pdays, previous, poutcome):
    # Encodage des caractéristiques catégorielles
    job_encoded = encoders[1].transform([job])[0]
    marital_encoded = encoders[2].transform([marital])[0]
    education_encoded = encoders[3].transform([education])[0]
    housing_encoded = encoders[4].transform([housing])[0]
